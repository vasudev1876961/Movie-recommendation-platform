    base_movie = copy.deepcopy(movies[i % 5])
    base_movie["id"] = i
    base_movie["title"] = f"{base_movie['title']} {i // 5 + 1}"
    base_movie["year"] = 1980 + (i % 5) * 10 + (i % 7)
    base_movie["rating"] = round(7.0 + (i % 20) * 0.1, 1)
    base_movie["popularity"] = round(40.0 + (i % 30) * 2.0, 1)
    
    # assign different genres
    genres_choices = [
      ["Action", "Sci-Fi", "Adventure"],
      ["Horror", "Mystery", "Thriller"],
      ["Comedy", "Romance"],
      ["Documentary"],
      ["Animation", "Fantasy", "Family"]
    ]
    base_movie["genres"] = genres_choices[i % 5]
    
    # Assign specific moods
    moods_choices = [
      ["Epic", "Adrenaline Rush"],
      ["Dark", "Spooky"],
      ["Funny", "Light & Fun"],
      ["Emotional"],
      ["Romantic"]
    ]
    base_movie["mood"] = moods_choices[i % 5]
    
